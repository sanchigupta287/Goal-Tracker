        "import os\n",
        "\n",
        "DATA_FILE = \"goals.txt\"\n",
        "\n",
        "def load_goals():\n",
        "    \"\"\"Reads saved goals from goals.txt line by line.\"\"\"\n",
        "    goals = []\n",
        "    if not os.path.exists(DATA_FILE):\n",
        "        return goals\n",
        "\n",
        "    with open(DATA_FILE, \"r\") as file:\n",
        "        for line in file:\n",
        "            line = line.strip()\n",
        "            if line:\n",
        "                parts = line.split(\",\")\n",
        "                if len(parts) == 5:\n",
        "                    goal = {\n",
