        "def view_goals(goals):\n",
        "    \"\"\"Module 2: Displays all tracked goals.\"\"\"\n",
        "    print(\"\\n--- YOUR GOALS ---\")\n",
        "    if not goals:\n",
        "        print(\"No goals found. Add one first!\")\n",
        "        return\n",
