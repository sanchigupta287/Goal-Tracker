        "    category = input(\"Enter Category (e.g., Academic, Fitness): \").strip()\n",
        "\n",
        "    goal_id = len(goals) + 1\n",
        "    new_goal = {\n",
        "        \"id\": goal_id,\n",
        "        \"title\": title,\n",
        "        \"category\": category,\n",
        "        \"progress\": 0,\n",
        "        \"status\": \"In Progress\"\n",
        "    }\n",
        "    goals.append(new_goal)\n",
        "    save_goals(goals)\n",
        "    print(f\"✅ Goal '{title}' added successfully!\")\n",
